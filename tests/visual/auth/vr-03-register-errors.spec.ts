import { test, expect } from '../../../src/support/fixtures';

test.describe('Auth visual', () => {
  test('VR-03: registration form validation errors state @auth', async ({ page, registerPage }) => {
    // 2. Open /auth/register, click register-submit and take a full-page screenshot
    await registerPage.goto();
    await registerPage.submit.click();

    // Wait on the verified message texts (same as TC-12; specs/auth.md "Verified facts"), not on unverified ids.
    for (const message of [
      'First name is required',
      'Last name is required',
      'Date of Birth is required',
      'Please enter a valid date in YYYY-MM-DD format.',
      'Country is required',
      'Postcode is required',
      'House number is required',
      'Street is required',
      'City is required',
      'State is required',
      'Phone is required.',
      'Email is required',
      'Password is required',
    ]) {
      await expect(page.getByText(message, { exact: true })).toBeVisible();
    }

    // NOTE (PWD-MIN): the baseline will contain the wrong text "Password must be minimal 6 characters long."
    // (the real minimum is 8). When PWD-MIN is fixed this screenshot must be regenerated by CI on request.
    await expect(page).toHaveScreenshot('VR-03-register-errors.png', {
      fullPage: true,
      mask: registerPage.dynamicWidgets,
    });
  });
});
